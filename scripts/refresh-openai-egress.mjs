#!/usr/bin/env node
// Rewrites the snapshot of OpenAI's published ChatGPT connector egress ranges, the addresses
// ChatGPT calls this MCP server from. The service re-reads the published list at runtime
// (PLATFORM_EGRESS_REFRESH_MINUTES); the snapshot is what it starts with.
//
// Usage: node scripts/refresh-openai-egress.mjs [already-downloaded.json]
import { readFileSync, writeFileSync } from "node:fs";
import { isIP } from "node:net";

const SOURCE = "https://openai.com/chatgpt-connectors.json";
const TARGET = new URL("../src/server/security/openaiConnectorEgress.ts", import.meta.url);

const text = process.argv[2]
  ? readFileSync(process.argv[2], "utf8")
  : await (await fetch(SOURCE, { headers: { accept: "application/json", "user-agent": "ai-audit-webmcp egress refresh" } })).text();
const document = JSON.parse(text);
const prefixes = (document.prefixes ?? [])
  .map((entry) => entry?.ipv4Prefix ?? entry?.ipv6Prefix)
  .filter((cidr) => typeof cidr === "string" && isIP(cidr.split("/")[0]) !== 0)
  .sort();
if (prefixes.length < 10) throw new Error(`only ${prefixes.length} prefixes; refusing to write a near-empty snapshot`);
const created = typeof document.creationTime === "string" ? document.creationTime : "undated";

writeFileSync(
  TARGET,
  `/**
 * OpenAI's published egress ranges for ChatGPT connectors: the addresses ChatGPT calls this MCP
 * server from. Generated by scripts/refresh-openai-egress.mjs; do not edit by hand.
 *
 * Source: ${SOURCE}
 * creationTime: ${created}
 *
 * This is what the service starts with. At runtime it re-reads the published list on the interval
 * PLATFORM_EGRESS_REFRESH_MINUTES sets, so a stale snapshot matters only until the first refresh.
 */
export const OPENAI_CONNECTOR_EGRESS_URL = ${JSON.stringify(SOURCE)};
export const OPENAI_CONNECTOR_EGRESS_CREATED = ${JSON.stringify(created)};
export const OPENAI_CONNECTOR_EGRESS: readonly string[] = [
${prefixes.map((cidr) => `  ${JSON.stringify(cidr)},`).join("\n")}
];
`,
);
console.log(`wrote ${prefixes.length} ranges (creationTime ${created}) to ${TARGET.pathname}`);
